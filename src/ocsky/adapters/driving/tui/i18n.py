class Tr:
    """Translates a key into the current language, with str.format placeholders filled in."""

    def __init__(self, lang: str = "en"):
        self.lang: str = lang if lang in STRINGS else "en"

    def __call__(self, key: str, **kw: object) -> str:
        """The text of key in this language. A key missing from the table is returned as it is."""
        text = STRINGS[self.lang].get(key)
        if text is None:
            return key
        return text.format(**kw)

    def next(self) -> Tr:
        """A translator for the next language in LANGS, wrapping around at the end."""
        return Tr(LANGS[(LANGS.index(self.lang) + 1) % len(LANGS)])
